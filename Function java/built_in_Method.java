public class built_in_Method {
    public static void main(String[] args) {
        // Math. vale built-in fnctions hote hai 

        System.out.println(Math.sqrt(4));
        double x = Math.sqrt(4);
        System.out.println(x);

        System.out.println(Math.cbrt(64)); //cube root

        System.out.println(Math.PI);

        System.out.println(Math.abs(-64));  //mod

        System.out.println(Math.floor(6.8));  //greatest integer function
        System.out.println(Math.floor(-7.8));
        System.out.println(Math.ceil(3.001));
        System.out.println(Math.ceil(-7.8));

        //important
        System.out.println(Math.min(3.78,9));
        System.out.println(Math.max(4,5));
        System.out.println(Math.pow(2,3));
        System.out.println(Math.round(6.7));
        System.out.println(Math.round(6.3));
        System.out.println(Math.exp(2));
        System.out.println(Math.log(10));
        System.out.println(Math.log10(100));
        System.out.println(Math.random());


    }
}
